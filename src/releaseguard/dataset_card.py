"""Generate a Hugging Face-format dataset card from real scan/redaction results.

Every number in the generated card comes from a `ScanResult`/`RedactionResult`
that already ran -- this module never invents a PII category, a file count,
or an entity type that wasn't actually detected. Fields the tool cannot know
(license, dataset description, intended use) are left as an explicit
`<!-- FILL IN -->` placeholder rather than a plausible-sounding guess.
"""

from __future__ import annotations

from datetime import datetime, timezone

import yaml

from releaseguard.types import RedactionResult, ScanResult

FILL_IN = "<!-- FILL IN: releaseguard cannot infer this -->"


def _yaml_frontmatter(entity_types: list[str]) -> str:
    metadata = {
        "license": FILL_IN,
        "tags": ["releaseguard-scanned"] + [f"pii:{e.lower()}" for e in entity_types],
    }
    return "---\n" + yaml.safe_dump(metadata, sort_keys=False) + "---\n"


def generate_dataset_card(
    scan_result: ScanResult,
    redaction_result: RedactionResult | None = None,
    dataset_name: str = FILL_IN,
) -> str:
    """Return a Hugging Face dataset card as a markdown string.

    Structure follows the standard Hugging Face dataset card sections
    (Dataset Summary, Dataset Structure, Privacy and PII handling,
    Licensing Information) -- see
    https://github.com/huggingface/huggingface_hub for the card format
    this mirrors.
    """
    entity_types = sorted(scan_result.entity_counts.keys())
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    lines: list[str] = [_yaml_frontmatter(entity_types), ""]
    lines.append(f"# Dataset Card for {dataset_name}")
    lines.append("")
    lines.append(f"_Generated by ReleaseGuard on {generated_at} from an actual PII/secret scan._")
    lines.append("")

    lines.append("## Dataset Summary")
    lines.append("")
    lines.append(FILL_IN)
    lines.append("")

    lines.append("## Dataset Structure")
    lines.append("")
    lines.append(f"- Files scanned: {scan_result.files_scanned}")
    if scan_result.files_skipped:
        skipped_count = len(scan_result.files_skipped)
        lines.append(f"- Files not scanned (no matching reader for the format): {skipped_count}")
    lines.append("")

    lines.append("## Privacy and Personally Identifiable Information (PII)")
    lines.append("")
    lines.append(
        f"Scanned with [Presidio](https://github.com/data-privacy-stack/presidio) via "
        f"ReleaseGuard (detector: `{scan_result.detector_name}`, "
        f"language: `{scan_result.language}`)."
    )
    lines.append("")
    if entity_types:
        lines.append("| Entity type | Occurrences found |")
        lines.append("| --- | --- |")
        for entity_type in entity_types:
            lines.append(f"| `{entity_type}` | {scan_result.entity_counts[entity_type]} |")
    else:
        lines.append("No PII entities were detected by Presidio at the configured score threshold.")
    lines.append("")

    if redaction_result is not None:
        lines.append(
            f"This dataset has been redacted (strategy: `{redaction_result.strategy}`). "
            f"{sum(redaction_result.entities_redacted.values())} entities were redacted "
            f"across {len(redaction_result.files_written)} files."
        )
    else:
        lines.append(
            "**This card describes the scan only. Run `releaseguard redact` before "
            "publishing if any PII was found above.**"
        )
    lines.append("")

    lines.append("## Licensing Information")
    lines.append("")
    lines.append(FILL_IN)
    lines.append("")

    lines.append("## Citation Information")
    lines.append("")
    lines.append(FILL_IN)
    lines.append("")

    return "\n".join(lines)
